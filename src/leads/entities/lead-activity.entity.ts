import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { ApiProperty } from '@nestjs/swagger';
import { HydratedDocument, Schema as MongooseSchema } from 'mongoose';

export type LeadActivityDocument = HydratedDocument<LeadActivity>;

@Schema({ timestamps: true, collection: 'lead_activities' })
export class LeadActivity {
  @ApiProperty({ example: 'lead_id_here', description: 'Lead ID' })
  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'Lead', required: true, index: true })
  leadId: string;

  @ApiProperty({ example: 'call', description: 'Activity type' })
  @Prop({
    enum: ['call', 'trial', 'website_visit', 'follow_up', 'message', 'note', 'status_change'],
    required: true,
  })
  type: string;

  @ApiProperty({ example: 'answered', description: 'Call/result outcome' })
  @Prop({ default: '' })
  outcome: string;

  @ApiProperty({ example: 'Discussed pricing and booked trial', description: 'Activity notes' })
  @Prop({ default: '' })
  notes: string;

  @ApiProperty({ example: 'staff_id_here', description: 'Actor (staff/admin) user ID', required: false })
  @Prop({ type: MongooseSchema.Types.ObjectId, ref: 'User', default: null })
  actorUserId: string | null;

  @ApiProperty({ example: 10, description: 'Score delta generated by this activity' })
  @Prop({ default: 0 })
  scoreDelta: number;

  @ApiProperty({ example: '2026-07-08T11:00:00Z', description: 'Interaction happened at' })
  @Prop({ default: Date.now })
  happenedAt: Date;
}

export const LeadActivitySchema = SchemaFactory.createForClass(LeadActivity);
